const raw = Object.fromEntries(
  Object.entries(source).map(([key, values]) => [
    key,
    Object.fromEntries(LANGS.map((lang, index) => [lang, values[index]])),
  ])
) as Record<string, Partial<Record<Lang, string>>>;

export type TranslationKey = string;

export function translate<K extends TranslationKey>(
  key: K,
  lang: Lang,
  vars?: Record<string, string | number>
): string {
  const entry = raw[key];
  let value = entry?.[lang] ?? entry?.en ?? key;
  if (vars) {
    for (const [name, replacement] of Object.entries(vars)) {
      value = value.replaceAll(`{${name}}`, String(replacement));
    }
  }
  return value;
}

export function isLang(value: string): value is Lang {
  return (LANGS as readonly string[]).includes(value);
}

export function isTranslationKey(value: string): value is TranslationKey {
  return value in raw;
}
